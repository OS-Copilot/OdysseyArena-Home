"""Write static/js/odyssey-curves.js from the digitized figure data.

    python3 tools/build_curves.py

Reads  tools/digitize/progress.json   success rate (profit for AI Trading)
                                      against step, every model plus the
                                      random policy, from the paper's Figure 4
                                      and its appendix version
       tools/digitize/loop.json       loop ratio against success rate, one
                                      point per model, from Figure 5
Both were digitized from the paper's vector PDFs by the scripts next to them
(extract_progress.py reads the matplotlib paths; digitize_loop.py reads the
embedded raster of the scatter figure). build_final.py prints the check of
every curve end and scatter point against Table 1.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "digitize"
OUT = ROOT / "static" / "js" / "odyssey-curves.js"

progress = json.loads((SRC / "progress.json").read_text())
loop = json.loads((SRC / "loop.json").read_text())

panels = []
for p in progress["panels"]:
    panels.append({
        "env": p["env"],
        "x_max": p["x_max"],
        "metric": "profit rate" if p["env"] == "AI Trading" else "success rate",
        "series": [{"model": s["model"], "points": s["points"]} for s in p["series"]],
        "random": p["random"],
    })
loops = []
for p in loop["panels"]:
    loops.append({
        "env": p["env"],
        "axes": p["axes"],
        "infeasible_axes_fraction": p["infeasible_axes_fraction"],
        "points": p["points"],
    })
data = {
    "source": "Digitized from the paper's figures by tools/digitize/; rebuilt by tools/build_curves.py. Do not edit.",
    "progress": {"panels": panels},
    "loop": {"panels": loops},
}
OUT.write_text("/* Generated by tools/build_curves.py from tools/digitize/*.json. Do not edit by hand. */\n"
               "window.ODYSSEY_CURVES = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.1f} KB)")
